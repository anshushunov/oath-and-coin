import type { ReactNode } from 'react';

/**
 * Две колонки равной ширины — раскладка отряда на оффере и панелей под полем боя.
 *
 * Класс `.columns` тот же, что уже держит ростер и ответы на экране оффера
 * (`styles.css`): правило одно, и кит пользуется им, а не заводит второе с теми же
 * тремя строками, которое разошлось бы с первым при первой правке.
 */
export function Columns({ children }: { readonly children: ReactNode }) {
  return <div className="columns">{children}</div>;
}

/**
 * Полоса: дети в один ряд, с переносом, когда ряд не помещается.
 *
 * `ASSUMPTION`: спека называет `Rail` без определения. Здесь это горизонтальный ряд —
 * рычаги, метрики и лестница действий в полосе пакета (Task 5) — а не боковая колонка:
 * две колонки уже даёт `Columns`, а ряда с переносом в ките иначе нет. Если Task 5 или 7
 * понадобится боковая колонка, это новый компонент, а не второе значение этого.
 *
 * Перенос, а не прокрутка вбок: горизонтальное переполнение — настоящий дефект, и
 * проверка достижимости обязана его видеть, поэтому ряд ничего не прячет.
 */
export function Rail({ children }: { readonly children: ReactNode }) {
  return <div className="rail">{children}</div>;
}
