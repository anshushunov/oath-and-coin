/**
 * Шкала кегля.
 *
 * Фиксированные значения в `rem` и ни одного `clamp`: шаг между ступенями — это решение,
 * которое должно быть видно в дереве, а не вычисляться из ширины окна в шести местах
 * по-разному.
 */
export const Type: Readonly<
  Record<'display' | 'title' | 'heading' | 'body' | 'caption' | 'micro', string>
> = {
  display: '1.75rem',
  title: '1.25rem',
  heading: '1rem',
  body: '0.875rem',
  caption: '0.75rem',
  micro: '0.6875rem'
};

/** Шаг вёрстки, в пикселях. Число, а не строка: канвас складывает их, CSS — нет. */
export const Space: Readonly<Record<'xs' | 'sm' | 'md' | 'lg' | 'xl' | 'xxl', number>> = {
  xs: 4,
  sm: 8,
  md: 12,
  lg: 16,
  xl: 24,
  xxl: 32
};

/** Толщина обводки, в пикселях. `thick` — та, что делает число читаемым на белой вспышке. */
export const Stroke: Readonly<Record<'hairline' | 'thick', number>> = {
  hairline: 2,
  thick: 3
};

/**
 * Роль как число, которое понимает Pixi.
 *
 * Единственное место в дереве, где `#rrggbb` превращается в `0xrrggbb`. Пока перевод
 * один, два вида одного цвета не могут разойтись; как только их станет два, смогут.
 */
export function hex(role: ColourRole): number {
  return Number.parseInt(Colour[role].slice(1), 16);
}

/**
 * Весь блок `:root{…}` целиком — тем же текстом, которым его печатает генератор.
 *
 * Возвращает строку, а не пишет файл, ровно для того, чтобы `tokens:generate` и
 * `tokens:check` сравнивали одно и то же: проверка, собирающая ожидаемый текст своим
 * способом, проверяет свой способ.
 */
export function cssVariables(): string {
  const kebab = (name: string): string =>
    name.replace(/[A-Z]/gu, (letter) => `-${letter.toLowerCase()}`);

  const declarations = [
    ...COLOUR_ROLES.map((role) => `  --${kebab(role)}: ${Colour[role]};`),
    '',
    ...Object.entries(Type).map(([name, size]) => `  --type-${name}: ${size};`),
    '',
    ...Object.entries(Space).map(([name, step]) => `  --space-${name}: ${String(step)}px;`),
    '',
    ...Object.entries(Stroke).map(([name, width]) => `  --stroke-${name}: ${String(width)}px;`)
  ];

  return `:root {\n${declarations.join('\n')}\n}`;
}
