/**
 * Цвет, кегль и шаг — объявленные один раз и больше нигде (`ADR-017`).
 *
 * **Зачем модуль существует.** [`DEC-018`](../../../../docs/decisions/DEC-018-colour-in-the-journal.md)
 * требует, чтобы журнал боя не имел собственной палитры и повторял константы канваса:
 * «синий = отряд» обязан быть одним фактом на две стороны шва. Пока факта два — один
 * в `pixi-scene.ts` числом `0xrrggbb`, другой в `.css` строкой `#rrggbb`, — они
 * разъезжаются молча. Это не гипотеза: до этого модуля три места независимо подобрали
 * почти один и тот же тёмный тон для роли «фон» (`0x11131a` на канвасе, `#101014` в окне
 * Electron, `#0d0f14` в `--surface`), ни одна пара не совпадала побайтово, и заметить это
 * мог только человек, открывший все три файла разом. Ни один тест такого не ловит: каждое
 * из трёх значений по отдельности совершенно корректно.
 *
 * Поэтому здесь объявление, а читатели — производные:
 *
 * - CSS получает `apps/web/src/ui/tokens.css`, напечатанный из {@link cssVariables}
 *   генератором `pnpm tokens:generate`; `pnpm tokens:check` краснеет, если файл на диске
 *   разошёлся с этим модулем;
 * - канвас Pixi получает числа из {@link hex} — единственного места в дереве, где перевод
 *   `#rrggbb` → `0xrrggbb` вообще происходит.
 *
 * Оба запрета механические, а не напоминание в код-ревью: ESLint не пускает цветовой
 * литерал в `.ts`/`.tsx` под `apps/web`, а `scripts/check-ui-colours.mjs` — в `.css`.
 * Исключения названы поимённо и их ровно два: этот файл и сгенерированный из него
 * `tokens.css`.
 *
 * Значения здесь — схематичная палитра, которую `DEC-007` просит до вертикального среза,
 * а не художественное направление. Менять их можно; объявлять их второй раз — нет.
 */

/**
 * Каждая роль цвета, по имени.
 *
 * Список и {@link Colour} держатся друг за друга типом: `Record<ColourRole, …>` не даст
 * добавить роль сюда, не назвав ей значение, и наоборот. Это единственная связь, которая
 * не требует, чтобы кто-то помнил про оба места.
 */
export const COLOUR_ROLES = [
  // Страница: поверхность, панель на ней, граница между ними и два веса текста.
  'surface',
  'panel',
  'edge',
  'ink',
  'inkDim',
  // Отказ — единственное, что на экране сохранений обязано быть замечено.
  'danger',
  // Канвас: собственный фон сцены, чтобы он не был дырой в странице.
  'sceneBackground',
  // Доска боя: клетка, две стороны, выбывший, полоса здоровья и метка состояния.
  'cell',
  'crew',
  'foe',
  'downed',
  'health',
  'healthEmpty',
  'status',
  // Всплывающее число урона и лечения с обводкой под ним (`COMBAT_SPEC` §10.2 п.4).
  'harm',
  'aid',
  'popupOutline',
  // Обводка на каждой фигуре, чтобы фишка на фоне всё-таки имела край.
  'outline',
  // Линия намерения на доске: кто на кого сейчас пойдёт. Свой цвет, не повторяющий ни
  // одной другой роли, — браузерная проверка находит линию по нему (`battle.spec.ts`).
  'intent',
  // Строка героя: что говорит «за», что «против» и что закрыто совсем.
  'favour',
  'against',
  'blocked'
] as const;

export type ColourRole = (typeof COLOUR_ROLES)[number];

